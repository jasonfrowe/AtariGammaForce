#!/usr/bin/env python3
"""Write romtest.bas: a 272K cart test (tests/romtest/build.sh builds it).

Every switched bank (2-16) holds a marker table and a routine that reads
it. The program, in bank 1 (always at $4000), reaches each bank two ways:
7800basic's bank gosub, and a direct write to $8000 as the game's
pf_stage does (the value is bank - 2) followed by a jsr. Bank 1's and the
last bank's (17, always at $C000) markers are read directly. Each bank
gets a line, OK or BAD; the last line sums it up. For headless runs,
`pass` holds 1 (all OK) or 2 (a bank failed).
"""
import os

LAST = 17
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "romtest.bas")


def sig(n):
    # each bank's marker: its number and a byte no other bank has
    return f"{n}, {(n * 37 + 11) & 255}"


L = []
w = L.append
w("  rem generated by romtest.py")
w("  set romsize 272k")
w("  displaymode 320A")
w("  set zoneheight 8")
w("  dim res = var0      ; via bank gosub, by bank")
w("  dim res2 = var20    ; via a direct $8000 write, by bank")
w("  dim pass = var40")
w("  dim chk = var41")
w("  BACKGRND = $00")
w("  P0C2 = $0F")
w("  P1C2 = $C8")
w("  P2C2 = $36")
w("  characterset atascii")
w("  alphachars ASCII")
w("  pass = 0")
w("")
w("  rem bank 1 (always in at $4000) and the last bank (always at $C000)")
w("  r = b1sig[0] : chk = b1sig[1] : if chk = b1sig_k then res[1] = r : res2[1] = r")
w(f"  r = b{LAST}sig[0] : chk = b{LAST}sig[1] : if chk = b{LAST}sig_k then res[{LAST}] = r : res2[{LAST}] = r")
w("  rem the switched banks, by 7800basic's bank gosub")
for n in range(2, LAST):
    w(f"  r = 0 : gosub b{n}chk bank{n} : res[{n}] = r")
w("  rem the switched banks, as the game switches them (pf_stage)")
w("  asm")
for n in range(2, LAST):
    w(f"  lda #{n - 2}")
    w("  sta $8000")
    w(f"  jsr b{n}asm")
    w(f"  sta res2+{n}")
w("  lda #0")
w("  sta $8000")
w("end")
w("")
w("  clearscreen")
w("  plotchars 'ATARI GAMMA FORCE 272K ROM TEST' 0 0 0")
w("  pass = 1")
for n in range(1, LAST + 1):
    row = n + 1
    w(f"  plotchars 'BANK {n:2d}' 0 8 {row}")
    w(f"  if res[{n}] = {n} && res2[{n}] = {n} then plotchars 'OK' 1 64 {row} else plotchars 'BAD' 2 64 {row} : pass = 2")
w("  if pass = 1 then plotchars 'ALL 17 BANKS OK' 1 0 20 else plotchars 'A BANK FAILED' 2 0 20")
w("")
w("main")
w("  drawscreen")
w("  goto main")
w("")
w("  data b1sig")
w(f"  {sig(1)}")
w("end")
w(f"  const b1sig_k = {(1 * 37 + 11) & 255}")
for n in range(2, LAST + 1):
    w("")
    w(f"  bank {n}")
    if n < LAST:
        w(f"b{n}chk")
        w(f"  chk = b{n}sig[1]")
        w(f"  if chk = {(n * 37 + 11) & 255} then r = b{n}sig[0]")
        w("  return")
        w("  asm")
        w(f"b{n}asm")
        w(f"  lda b{n}sig+1")
        w(f"  cmp #{(n * 37 + 11) & 255}")
        w(f"  bne b{n}bad")
        w(f"  lda b{n}sig")
        w("  rts")
        w(f"b{n}bad")
        w("  lda #0")
        w("  rts")
        w("end")
    else:
        w("  incgraphic atascii.png 320A")
        w(f"  const b{n}sig_k = {(n * 37 + 11) & 255}")
    w(f"  data b{n}sig")
    w(f"  {sig(n)}")
    w("end")

with open(OUT, "w") as f:
    f.write("\n".join(L) + "\n")
print("wrote", OUT)
